// 前提(判明分):
// ・効果は「打撃前の温度」で判定され、次に温度が変わるまで持続する(4連打ちなど複数マス同時ヒットにも同じ効果が適用される)
// ・集中力変化(shuchu):温度が400の倍数→集中力消費0.5倍。200の倍数かつ400の倍数でない→集中力消費1.5倍+会心率+400%(5倍)。威力の数値そのものへの影響はなし。
// ・たたき変化(tataki):温度が400の倍数→威力2倍。200の倍数かつ400の倍数でない→威力0.5倍(端数切り上げ)。会心が乗る場合は「たたき変化補正→切り上げ→会心の2倍」の順。
// ・威力会心率上昇(kaishin):温度が200の倍数になるたびに、ゾーン未到達のマスがランダムに1つ点灯(再抽選)。点灯マスは威力2倍+会心率大幅上昇。非点灯マスは特性なしと同じ。
// ・メーター減少・戻り(modori):温度が200の倍数になった時(始まりの1000℃は除く)、1マスの値が減る。
//   対象は、ゾーンを超えたマスがあれば上限から最も離れたマス、無ければ未到達のうちゾーンに最も近いマス。
//   値が0のマスは減らせないので対象にならない。値のあるマスが1つも無ければ戻りは起きない
//   (利用者の情報: 何かしら値が入っているマスが候補になる。全マス0のまま火力上げ2回で1600℃に着いても起きない)。
//   減る量は素材ごとに決まった範囲の中から乱数(PRESETS の modori)。超過したマスもこれで取り戻せる。
/* ---- 戻り(modori) ---- */
const MODORI_DEFAULT = { min: 12, max: 16 };      // 素材に指定が無い時の仮の範囲
function modoriRange(){
  const p = PRESETS[G.preset];
  return (p && p.modori) || MODORI_DEFAULT;
}
// 戻りの対象マス。ゾーンを超えたマスがあれば上限から最も離れたマス、無ければ未到達で値のある(0でない)
// マスのうちゾーンに最も近いマス。距離が同じなら番号の小さいマス(ゲームでの扱いは未確認)。
// 使わないマス(ゾーン 0〜0)は対象にしない。対象が無ければ null(戻りは起きない)。
function modoriTarget(ms){
  let oi = -1, od = 0;
  for(let i = 0; i < ms.length; i++){
    const m = ms[i]; if(m.zoneHigh <= 0) continue;
    const d = m.current - m.zoneHigh;
    if(d > od){ od = d; oi = i; }
  }
  if(oi >= 0) return oi;
  let ci = -1, cd = Infinity;
  for(let i = 0; i < ms.length; i++){
    const m = ms[i]; if(m.zoneHigh <= 0) continue;
    if(m.current <= 0) continue;               // 0のマスは減らせないので候補にならない
    const d = m.zoneLow - m.current;
    if(d > 0 && d < cd){ cd = d; ci = i; }
  }
  return ci >= 0 ? ci : null;
}
// 手を打った後に呼ぶ。温度が200の倍数になっていれば戻りを起こし、{マス, 量} を返す。
// 対象になるマスが無い時(超過が無く、値のある未到達のマスも無い。全マス0の時など)は起きないので null。
// 始まりの1000℃では起きないが、この関数は打った後にしか呼ばないので自然にそうなる。
function applyModori(ms, temp, trait, rnd){
  if(trait !== 'modori' || temp <= 0 || temp % 200 !== 0) return null;
  const i = modoriTarget(ms);
  if(i === null) return null;
  const r = modoriRange();
  const amt = r.min + Math.floor(rnd() * (r.max - r.min + 1));
  ms[i].current = Math.max(0, ms[i].current - amt);
  return { i, amt };
}
// 1マスを打った直後に取りうる値(通常・会心)。
// 会心は理想値を通り越すと理想値で止まるので、ゾーンの上限を超えることは無い。
// 会心の値は「理想値の手前で止まった 前の値+2×ロール(ゾーン未満)」か「ゾーン内の値」。
// 既にゾーンに入っている(超えている)マスは、理想値以上なら会心でも動かない(ゲームでは miss と出る。
// 攻略記事: まさとるてぃあ「虹色のオーブ打ち方手順例」の必殺の検証、日替わりゲーミング本部「虹色のオーブ」その5)。
function hitOutcomes(before, rolls, zoneLow, zoneHigh){
  const normal = new Set(), crit = new Set();
  for(const r of rolls){ normal.add(before + r); if(before + 2*r < zoneLow) crit.add(before + 2*r); }
  const top = before + 2*rolls[rolls.length-1];
  for(let v = Math.max(zoneLow, before + 1); v <= zoneHigh && v <= top; v++) crit.add(v);
  if(before >= zoneLow) crit.add(before);
  return { normal: [...normal].sort((a,b)=>a-b), crit: [...crit].sort((a,b)=>a-b) };
}
// 打った結果の全ての組み合わせについて戻りの対象を求める。
// outcomes は {マス番号: 取りうる値の配列}。打っていないマスは今の値のまま。
// 返り値の Set は対象になりうるマス。付随して、打ったマスごとに
//   asTarget[i]: そのマスが対象になる時の、打った直後の値
//   asOther[i] : そのマスが対象にならない時の、打った直後の値
// を持たせる(入力の候補を、実際に起こりうるものだけに絞るため)。
// none は「戻りが起きない組み合わせがある」(全マスがゾーンに入った・値のあるマスが無い)。
function possibleModoriTargets(ms, outcomes){
  const idx = Object.keys(outcomes).map(Number);
  const vals = idx.map(i => [...new Set(outcomes[i])]);
  const cur = ms.map(m => ({ current: m.current, zoneLow: m.zoneLow, zoneHigh: m.zoneHigh }));
  const found = new Set(), asTarget = {}, asOther = {};
  let none = false;
  for(const i of idx){ asTarget[i] = new Set(); asOther[i] = new Set(); }
  let budget = 400000;                 // 組み合わせが多すぎる時の打ち切り(4マス×25通りでも収まる)
  (function rec(k){
    if(budget-- <= 0){ none = true; return; }      // 数え切れない時は「起きないかも」として扱う
    if(k === idx.length){
      const t = modoriTarget(cur);
      if(t !== null) found.add(t); else none = true;
      for(const i of idx) (i === t ? asTarget : asOther)[i].add(cur[i].current);
      return;
    }
    for(const v of vals[k]){ cur[idx[k]].current = v; rec(k + 1); }
  })(0);
  found.asTarget = asTarget; found.asOther = asOther; found.none = none;
  return found;
}
// 手 x を打った後に起きる戻りで、未到達のマスが失う量の見込み(打つマスは中央のロールで進んだとみなす)。
// 戻りが起きない・超過したマスに来る(取り戻しになる)時は 0。
function modoriLossAfter(ms, x, t, cfg){
  if(!(x.nt > 0) || x.nt % 200 !== 0) return 0;
  const after = ms.map(m => ({ current: m.current, zoneLow: m.zoneLow, zoneHigh: m.zoneHigh }));
  for(const i of x.tg){
    const r = rollsForMass(x.sk, t, cfg.trait, i);
    if(r) after[i].current += r[Math.floor(r.length/2)];
  }
  const i = modoriTarget(after);
  if(i === null || after[i].current > after[i].zoneHigh) return 0;
  const rg = modoriRange();
  return Math.min(after[i].current, (rg.min + rg.max) / 2);
}
// 盤面が仕上がったか。戻りの地金では超過も取り戻せるので、超過が残る間は仕上がりとしない。
function boardDone(ms, trait){
  if(!ms.every(m => m.current >= m.zoneLow)) return false;
  return trait !== 'modori' || ms.every(m => m.current <= m.zoneHigh);
}
// 戻りの地金で、全マスがゾーンに届いたのに超過が残っている時の手。
// 戻りを起こすには温度を200の倍数に合わせる必要があり、打てるマスが無いので温度操作だけで合わせる。
// 火力上げ・冷やし込みを最大2手組み合わせ、200の倍数に着く最安の1手目を返す。着けなければ null。
function modoriRecover(ms, f, t, cfg){
  const ops = SKILLS.filter(s => s.masses === 0 && s.lv <= cfg.level);
  let best = null, bc = Infinity;
  for(const a of ops){
    const ca = actualCostOf(a, t, cfg.trait), ta = t + a.tempDelta;
    if(ca > f || ta <= 0) continue;
    if(ta % 200 === 0){ if(ca < bc){ bc = ca; best = { sk: a, tg: [], c: ca, nt: ta, overP: 0 }; } continue; }
    for(const b of ops){
      const cb = actualCostOf(b, ta, cfg.trait), tb = ta + b.tempDelta;
      if(ca + cb > f || tb <= 0 || tb % 200 !== 0) continue;
      if(ca + cb < bc){ bc = ca + cb; best = { sk: a, tg: [], c: ca, nt: ta, overP: 0 }; }
    }
  }
  return best;
}

// 威力会心率上昇で、手 x の後に着く温度(200の倍数)で点灯しうる未到達マスのうち、
// 点灯したら狙い系の技で仕上げられる位置(会心なら理想値で止まり、会心でなくても超えない)にいるマスの割合。
// 打つマスは中央のロールで進んだとみなす。重み litReady で評価に足す(既定 0)。
// 点灯マスで仕上げると誤差0の率が約9割あるのに、点灯した時にそのマスが仕上げ位置にいたのは
// 輝紋章の盾で4.1%だけだった(点灯の73%はゾーンまで100以上離れたマスに当たっていた)。
function litReadyFrac(ms, x, t, f, cfg){
  if(cfg.trait !== 'kaishin' || !(x.nt > 0) || x.nt % 200 !== 0) return 0;
  const after = ms.map(m => ({ current: m.current, zoneLow: m.zoneLow, zoneHigh: m.zoneHigh }));
  for(const i of x.tg){
    if(after[i].current >= after[i].zoneLow) continue;
    const r = rollsForMass(x.sk, t, cfg.trait, i);
    if(r) after[i].current += r[Math.floor(r.length/2)];
  }
  const fa = f - x.c;
  let un = 0, ready = 0;
  for(let i = 0; i < after.length; i++){
    const m = after[i];
    if(m.zoneHigh <= 0 || m.current >= m.zoneLow) continue;
    un++;
    for(const sk of SKILLS){
      if(!sk.crit || sk.masses !== 1 || sk.lv > cfg.level) continue;
      if(actualCostOf(sk, x.nt, cfg.trait) > fa) continue;
      const r = getRollCandidates(sk, x.nt, cfg.trait, true);
      if(r && m.current + r[r.length-1] <= m.zoneHigh && m.current + 2*r[0] >= m.zoneHigh){ ready++; break; }
    }
  }
  return un ? ready / un : 0;
}

// 戻りの地金で、ゾーン内にあるマスをわざと超過させ、直後の戻り(一番超えたマスが12〜16減る)で
// ゾーンの手前に戻して打ち直す手。会心でゾーンに入ったマスは理想値ちょうどなので、
// 理想値の見込み(G.posts)から期待誤差を求め、P.redoMin 以上のマスだけを対象にする。
// 条件: 1マス技で必ず超過し、打った後の温度が200の倍数(=すぐ戻りが起きる)で、戻りの対象がそのマスになる。
//       打った後に集中力が P.redoF 以上残る。
function massExpErr(i, m){
  const n = m.zoneHigh - m.zoneLow + 1;
  const p = (G.posts && G.posts[i] && G.posts[i].length === n) ? G.posts[i] : null;
  let e = 0;
  for(let k = 0; k < n; k++) e += (p ? p[k] : 1/n) * massError(m.current, m.zoneLow + k, m.zoneLow, m.zoneHigh);
  return e;
}
function modoriRedo(ms, f, t, P, cfg){
  let best = null, bv = -1;
  for(let i = 0; i < ms.length; i++){
    const m = ms[i];
    if(m.zoneHigh <= 0 || m.current < m.zoneLow || m.current > m.zoneHigh) continue;
    const ee = massExpErr(i, m);
    if(ee < P.redoMin) continue;
    for(const sk of SKILLS){
      if(sk.masses !== 1 || !sk.key || sk.crit || sk.lv > cfg.level) continue;   // 会心で大きく超えないよう狙い系は使わない
      const c = actualCostOf(sk, t, cfg.trait);
      if(c > f || f - c < P.redoF) continue;
      const nt = Math.max(0, t + sk.tempDelta);
      if(!(nt > 0) || nt % 200 !== 0) continue;
      const r = rollsForMass(sk, t, cfg.trait, i);
      if(!r || m.current + r[0] <= m.zoneHigh) continue;          // 必ず超過する
      if(m.current + r[r.length-1] - modoriRange().min > m.zoneHigh) continue;   // 一番少ない戻りでも超過が解ける
      const after = ms.map(x => ({ current: x.current, zoneLow: x.zoneLow, zoneHigh: x.zoneHigh }));
      after[i].current = m.current + r[0];
      if(modoriTarget(after) !== i) continue;                      // 戻りがこのマスに来る
      const v = ee - c / 100;                                       // 誤差の大きいマスを、安い手で
      if(v > bv){ bv = v; best = { sk, tg: [i], c, nt, overP: 1, redo: true }; }
    }
  }
  return best;
}

// ===================== 残り1マスの仕上げ(総当たりの最善、lastDP・lastDProll、既定で使う) =====================
// 残り1マスになると、温度も集中力もすべてそのマスに使える。1マスだけなら状態(ゾーン下限までの残り距離 g・
// 温度 T・集中力 F)が小さいので、打てる手をすべて総当たりで比べて最善の手を選べる(動的計画法)。
// 実測(ブルームシールド・貪欲 2000局): 残り1マスの時点から誤差0で仕上がる割合は、エンジン 51.9% に対して最善 68.8%。
// 評価は「全体で大成功になる確率」。先に仕上げたマスの誤差の合計は、理想値の推定(G.posts)から分布を出し、
// 最後のマスに許される誤差(許容誤差 − 先のマスの誤差)ごとの表を混ぜて使う。
// 地金特性の効果(会心ターン・消費の増減・威力の増減・点灯)は、そのまま計算に入れる。理想値はゾーン内で一様とみなす。
// 戻りの地金は、状態に「ゾーンを超えた量」を足した版で計算する(ldpQM。下の説明を参照)。
// 表は必要になった分だけ作り、同じ条件なら使い回す。lastDProll が 0 なら先読みの中の打ち手では使わない。
// 省力化(表は Worker ごとに持つので、作る時間とメモリが1回目の計算の重さになる):
// ・集中力は ldpF(既定 120)で頭打ちにする。最後の1マスにそれ以上は使い切れない
//   (貪欲 3000局で 200 と比べ、ブルーム・樹液・ひだねとも 99.8% 以上の局が同じ結果)。
// ・先読みの中は、許される誤差のうち一番ありそうな1つの表だけを使い、集中力は ldpFR(既定 80)で頭打ち。
// ・値は 0〜65535 の整数(2バイト)で持つ。表の合計が LDP_CACHE_MAX を超えたら、長く使っていない表から捨てる。
//   省力化の前は、1回目の計算に 樹液 +3.9秒・オーブ +22秒、表のメモリが Worker 1つあたり 28〜102MB かかっていた
//   (今は +0.7〜2.2秒・2〜5MB)。商材ごとのコメントにある先読みありの成績は、省力化の前の版で測った値。
// ・候補選び(mcPrepare)は Worker で行う(mc-pool.js)。画面のスレッドで表を作ると最大4秒止まっていた。
const LDP_TMAX = 2200, LDP_GMAX = 160, LDP_NT = LDP_TMAX / 50;     // 温度 50〜2200℃(50刻み)
const LDP_SCALE = 65535, LDP_INV = 1 / 65535;
// 表の合計の上限。アプリ(Worker)のメモリを抑えるための値。検証のスクリプト(tools/analyze.js・tools/tune.js・tests/sim.js)は
// 読み込んだ後に大きくする(LDP_CACHE_TEST_MB)。上限を超えると表を捨てて作り直すだけなので、上限を変えても結果は変わらない。
//   上限 24MB では、戻りの地金(表が大きい)で作り直しを繰り返していた。4GB にすると 奇跡の鍛冶ハンマー 100局が約8分 → 19秒、
//   記録は全局同じ(奇跡の鍛冶ハンマー・虹色のオーブ 各300局で確かめた)。1本の処理のメモリは最大 190MB ほど。
let LDP_CACHE_MAX = 24 * 1048576;
const LDP_CACHE_TEST_MB = 4096;
const LDP_HIT_IDS = ['tataku', 'tekagen', 'nibai', 'sanbai', 'nerai', 'reppuu', 'yowanerai'];
const LDP_CACHE = new Map();
let IN_ROLLOUT = 0;                      // 先読みの試行の中か(mcRollout・tracedRollout が数える)
function ldpTable(L, H, a, cfg){
  const mod = cfg.trait === 'modori' ? modoriRange() : null;
  const key = [L, H, a, cfg.level, cfg.hammerId, cfg.star, cfg.trait].join('|') + (mod ? '|' + mod.min + '|' + mod.max : '');
  let tb = LDP_CACHE.get(key);
  if(tb){ LDP_CACHE.delete(key); LDP_CACHE.set(key, tb); return tb; }
  const w = H - L + 1, big = a >= MAX_ERR;          // 誤差は4で頭打ちなので、許される誤差が4以上ならゾーン内はどこでも良い
  const pIn = new Float64Array(w), pCrit = new Float64Array(w);
  for(let v = L; v <= H; v++){
    let n1 = 0, n2 = 0;
    for(let id = L; id <= H; id++){
      if(big || Math.abs(v - id) <= a) n1++;
      if(v >= id || big || id - v <= a) n2++;       // 会心は理想値を越えれば理想値で止まる。届かなければ v に止まる
    }
    pIn[v - L] = n1 / w; pCrit[v - L] = n2 / w;
  }
  // 手ごとの温度別の 消費・打った後の温度・ロール・会心率(開始直後ではない前提で計算する)
  const saved = simFirstMove; simFirstMove = false;
  const acts = [];
  for(const id of [...LDP_HIT_IDS, 'karyoku', 'hiyashikomi']){
    const sk = SKILLS.find(x => x.id === id);
    if(!sk || sk.lv > cfg.level) continue;
    const rows = [];
    for(let ti = 0; ti < LDP_NT; ti++){
      const T = (ti + 1) * 50, nt = T + sk.tempDelta;
      const row = { c: actualCostOf(sk, T, cfg.trait), nti: (nt > 0 && nt <= LDP_TMAX) ? nt / 50 - 1 : -1 };
      // 威力会心率上昇: 残り1マスなら、200の倍数の温度で光るのは必ずそのマス(ロール2倍・会心率上昇)
      const lit = cfg.trait === 'kaishin' && T % 200 === 0;
      if(sk.key){ row.r = getRollCandidates(sk, T, cfg.trait, lit);
                  row.cr = computeCritRate(sk, cfg.level, cfg.hammerId, cfg.star, cfg.trait, T, lit); }
      else if(row.nti < 0) row.skip = true;                                   // 温度の範囲の外へは動かさない
      rows.push(row);
    }
    acts.push({ sk, rows });
  }
  simFirstMove = saved;
  tb = { L, H, w, pIn, pCrit, acts, V: [], bytes: 0 };
  if(mod){
    tb.mod = mod; tb.GM = LDP_GM_M; tb.S = LDP_GM_M + LDP_OM + 1;
    tb.smLo = Math.max(0, L - LDP_GM_M); tb.smHi = H + LDP_OM + mod.max; tb.smN = tb.smHi - tb.smLo + 1;
  }
  LDP_CACHE.set(key, tb);
  return tb;
}
const ldpIdx = (ti, g) => ti * (LDP_GMAX + 1) + g;
// 手 act を、温度 ti・残り g・集中力 F で打った時の価値
function ldpQ(tb, act, ti, g, F){
  const row = act.rows[ti];
  if(row.skip || row.c > F) return -1;
  const F2 = F - row.c, V2 = tb.V[F2];
  if(!act.sk.key) return V2[ldpIdx(row.nti, g)] * LDP_INV;
  const L = tb.L, H = tb.H, c = L - g, r = row.r, cr = row.cr, nti = row.nti;
  let s = 0;
  for(let k = 0; k < r.length; k++){
    const v = c + r[k], v2 = c + 2*r[k];
    const a = v > H ? 0 : (v >= L ? tb.pIn[v - L] : (nti < 0 ? 0 : V2[ldpIdx(nti, L - v)] * LDP_INV));
    const b = v2 >= L ? (v2 >= H ? 1 : tb.pCrit[v2 - L]) : (nti < 0 ? 0 : V2[ldpIdx(nti, L - v2)] * LDP_INV);
    s += (1 - cr) * a + cr * b;
  }
  return s / r.length;
}
function ldpEnsure(tb, F){
  while(tb.V.length <= F){
    const Fc = tb.V.length, arr = new Uint16Array(LDP_NT * (LDP_GMAX + 1));
    tb.V.push(arr); tb.bytes += arr.byteLength;   // 消費は1以上なので、同じ集中力の値は参照しない
    for(let ti = 0; ti < LDP_NT; ti++) for(let g = 1; g <= LDP_GMAX; g++){
      let best = 0;
      for(const act of tb.acts){ const q = ldpQ(tb, act, ti, g, Fc); if(q > best) best = q; }
      arr[ldpIdx(ti, g)] = Math.round(best * LDP_SCALE);
    }
  }
}
// ---- 戻りの地金の版 ----
// 残り1マスなら、200の倍数の温度で起きる戻りの対象は必ずそのマス(ほかのマスはゾーン内なので対象にならない)。
// ゾーンの手前にいれば12〜16減り(損)、ゾーンを超えていれば減って取り戻せる(超過は失敗で終わらない)。
// そこで状態の「残り g」に「超えた量 o」を足す(位置 p = g、または GM + o)。戻りの量は範囲の中で等しい確率とみなす。
// 超えている間は打たず(ゲームでも打たない)、温度操作で200の倍数に着けて戻りを待つ。ゾーンに入れば戻りは起きない。
// みだれ打ちは仕上がったマスにも当たるので使わない。残りが GM、超えた量が OM を超えたら失敗とみなす
// (GM は残り160から戻り1回分、OM は1回の打撃で超えうる量。どちらもまず起きない)。
const LDP_GM_M = LDP_GMAX + 16, LDP_OM = 90;
// 値 c で温度 nti に着いた時の価値(戻りの前)
function ldpAtM(tb, V2, nti, c){
  if(c >= tb.L && c <= tb.H) return tb.pIn[c - tb.L];
  if(nti < 0) return 0;
  if(c < tb.L){ const g = tb.L - c; return g <= tb.GM ? V2[nti * tb.S + g] * LDP_INV : 0; }
  const o = c - tb.H; return o <= LDP_OM ? V2[nti * tb.S + tb.GM + o] * LDP_INV : 0;
}
// 戻りを入れた価値。md は着いた温度が200の倍数か。ゾーン内と値0のマスには戻りが起きない
function ldpAfterM(tb, V2, nti, md, c){
  if(!md || c <= 0 || (c >= tb.L && c <= tb.H)) return ldpAtM(tb, V2, nti, c);
  let s = 0;
  for(let k = tb.mod.min; k <= tb.mod.max; k++) s += ldpAtM(tb, V2, nti, Math.max(0, c - k));
  return s / (tb.mod.max - tb.mod.min + 1);
}
// 表を作る間は、戻りの平均(12〜16の5通り)を層ごとに前もって求めておき、1回の参照で済ませる。
// sm は200の倍数の温度(11通り)× 値 c(smLo〜smHi)の「戻りを入れた価値」
function ldpSmoothM(tb, V2){
  const sm = new Float32Array((LDP_NT / 4) * tb.smN);
  for(let m = 0; m < LDP_NT / 4; m++){
    const nti = m * 4 + 3;
    for(let c = tb.smLo; c <= tb.smHi; c++) sm[m * tb.smN + c - tb.smLo] = ldpAfterM(tb, V2, nti, true, c);
  }
  return sm;
}
function ldpAfterSM(tb, V2, nti, md, sm, c){
  if(sm && c >= tb.smLo && c <= tb.smHi) return sm[((nti + 1) / 4 - 1) * tb.smN + c - tb.smLo];
  return ldpAfterM(tb, V2, nti, md, c);
}
// smOf は表を作る間だけ渡す(層ごとの前計算を返す)。最後の手を選ぶ時は渡さずにそのまま計算する
function ldpQM(tb, act, ti, p, F, smOf){
  const row = act.rows[ti];
  if(row.skip || row.c > F) return -1;
  const over = p > tb.GM;
  if(over && act.sk.key) return -1;
  const F2 = F - row.c, V2 = tb.V[F2], nti = row.nti, md = nti >= 0 && (nti + 1) % 4 === 0;
  const sm = md && smOf ? smOf(F2) : null;
  const c = over ? tb.H + (p - tb.GM) : tb.L - p;
  if(!act.sk.key) return ldpAfterSM(tb, V2, nti, md, sm, c);
  const r = row.r, cr = row.cr, L = tb.L, H = tb.H;
  let s = 0;
  for(let k = 0; k < r.length; k++){
    const v2 = c + 2*r[k];
    // 会心はゾーンに届けば理想値で止まる(ゾーン内なので戻りは起きない)。届かなければ手前に止まり、戻りを受けうる
    const b = v2 >= L ? (v2 >= H ? 1 : tb.pCrit[v2 - L]) : ldpAfterSM(tb, V2, nti, md, sm, v2);
    s += (1 - cr) * ldpAfterSM(tb, V2, nti, md, sm, c + r[k]) + cr * b;
  }
  return s / r.length;
}
function ldpEnsureM(tb, F){
  if(tb.V.length > F) return;
  const cache = new Map();
  const smOf = F2 => { let x = cache.get(F2); if(!x){ x = ldpSmoothM(tb, tb.V[F2]); cache.set(F2, x); } return x; };
  const ops = tb.acts.filter(a => !a.sk.key);          // 超えている間は温度操作だけ
  while(tb.V.length <= F){
    const Fc = tb.V.length, arr = new Uint16Array(LDP_NT * tb.S);
    tb.V.push(arr); tb.bytes += arr.byteLength;
    for(let ti = 0; ti < LDP_NT; ti++) for(let p = 1; p < tb.S; p++){
      if(p <= tb.GM && p > tb.L) continue;          // 値が負になる位置は起きない
      let best = 0;
      for(const act of (p > tb.GM ? ops : tb.acts)){ const q = ldpQM(tb, act, ti, p, Fc, smOf); if(q > best) best = q; }
      arr[ti * tb.S + p] = Math.round(best * LDP_SCALE);
    }
    cache.delete(Fc - 40);                            // 消費は多くても30ほどなので、古い層の前計算は捨てる
  }
}
// 表の合計が上限を超えたら、長く使っていない表から捨てる(keep は今使う表)
function ldpTrim(keep){
  let total = 0;
  for(const tb of LDP_CACHE.values()) total += tb.bytes;
  if(total <= LDP_CACHE_MAX) return;
  for(const [k, tb] of LDP_CACHE){
    if(total <= LDP_CACHE_MAX * 0.75) break;
    if(keep.includes(tb)) continue;
    LDP_CACHE.delete(k); total -= tb.bytes;
  }
}
// 先に仕上げたマス(i 以外)の誤差の合計の分布 [P(0), P(1), …, P(th)]。超過したマスがあれば null
function finishedErrDist(ms, i, th, i2){
  let dist = [1];
  for(let j = 0; j < ms.length; j++){
    const m = ms[j];
    if(j === i || j === i2 || m.zoneHigh <= 0) continue;
    if(m.current > m.zoneHigh) return null;
    const n = m.zoneHigh - m.zoneLow + 1;
    const p = (G.posts && G.posts[j] && G.posts[j].length === n) ? G.posts[j] : null;
    const e = new Array(MAX_ERR + 1).fill(0);
    for(let k = 0; k < n; k++) e[Math.min(Math.abs(m.current - (m.zoneLow + k)), MAX_ERR)] += p ? p[k] : 1 / n;
    const nd = new Array(th + 1).fill(0);
    for(let x = 0; x < dist.length; x++) for(let y = 0; y <= MAX_ERR; y++) if(x + y <= th) nd[x + y] += dist[x] * e[y];
    dist = nd;
  }
  return dist;
}
// 表の混ぜ合わせ(mix)で手 x を打った時の価値。火力上げ・冷やし込みは、次の手で反対の温度操作を打たない前提で求める
// (表の値は打てる前提なので、そのまま使うと「火力上げ → 冷やし込み×2」のような遠回りを選び、次の手番でそれを
// 禁じると悪い局面に入ってしまう)。打てない手は -1。
function ldpQNoUndo(mix, x, ti, p, F, cfg){
  const act = mix[0].tb.acts[x];
  const plain = () => { let q = 0; for(const e of mix){ const v = ldpQ(e.tb, e.tb.acts[x], ti, p, F); if(v < 0) return -1; q += e.w * v; } return q; };
  if(act.sk.key || cfg.trait === 'modori' || cfg.trait === 'kaishin') return plain();
  const row = act.rows[ti];
  if(row.skip || row.c > F || row.nti < 0) return -1;
  const F2 = F - row.c, opp = act.sk.id === 'karyoku' ? 'hiyashikomi' : act.sk.id === 'hiyashikomi' ? 'karyoku' : null;
  let best = -1;
  for(let y = 0; y < mix[0].tb.acts.length; y++){
    if(mix[0].tb.acts[y].sk.id === opp) continue;
    let q = 0, ok = true;
    for(const e of mix){ const v = ldpQ(e.tb, e.tb.acts[y], row.nti, p, F2); if(v < 0){ ok = false; break; } q += e.w * v; }
    if(ok && q > best) best = q;
  }
  return best < 0 ? 0 : best;
}
function lastMassMove(ms, f, t, P, cfg){
  if(isStartState()) return null;
  const mod = cfg.trait === 'modori';
  const open = [], over = [];
  for(let j = 0; j < ms.length; j++){
    if(ms[j].zoneHigh <= 0) continue;
    if(ms[j].current < ms[j].zoneLow) open.push(j); else if(ms[j].current > ms[j].zoneHigh) over.push(j);
  }
  // 残り1マス(ほかはゾーン内)。戻りの地金では、残りの1マスがゾーンを超えている時も戻りで取り戻す道を計算する
  let i, p;
  if(open.length === 1 && !over.length){
    i = open[0]; p = ms[i].zoneLow - ms[i].current;
    if(p < 1 || p > LDP_GMAX) return null;
  } else if(mod && !open.length && over.length === 1){
    i = over[0]; const o = ms[i].current - ms[i].zoneHigh;
    if(o > LDP_OM) return null;
    p = LDP_GM_M + o;
  } else return null;
  const m = ms[i];
  if(t % 50 !== 0 || t < 50 || t > LDP_TMAX) return null;
  const th = SUCCESS_THRESHOLD, dist = finishedErrDist(ms, i, th);
  if(!dist) return null;
  const roll = IN_ROLLOUT > 0;
  const F = Math.min(f, roll ? (P.ldpFR || 80) : (P.ldpF || 120)), ti = t / 50 - 1;
  // 最後のマスに許される誤差 a = th − (先のマスの誤差) ごとの表を、その確率で混ぜる。
  // 先読みの中は一番ありそうな a の表1枚だけにする
  let ks = [];
  if(roll){ let kb = 0; for(let k = 1; k <= th; k++) if(dist[k] > dist[kb]) kb = k; if(dist[kb] > 1e-6) ks = [kb]; }
  else for(let k = 0; k <= th; k++) if(dist[k] > 1e-6) ks.push(k);
  const mix = [];
  for(const k of ks){
    const tb = ldpTable(m.zoneLow, m.zoneHigh, Math.min(th - k, MAX_ERR), cfg);
    if(mod) ldpEnsureM(tb, F); else ldpEnsure(tb, F);
    mix.push({ w: roll ? 1 : dist[k], tb });
  }
  if(!mix.length) return null;
  ldpTrim(mix.map(e => e.tb));
  let best = null, bq = 0;
  for(let x = 0; x < mix[0].tb.acts.length; x++){
    if(undoesPrev(mix[0].tb.acts[x].sk, cfg)) continue;
    let q = 0, ok = true;
    if(!mod) q = ldpQNoUndo(mix, x, ti, p, F, cfg);
    if(q < 0) ok = false;
    else if(mod) for(const e of mix){ const v = ldpQM(e.tb, e.tb.acts[x], ti, p, F); if(v < 0){ ok = false; break; } q += e.w * v; }
    if(ok && q > bq){ bq = q; best = mix[0].tb.acts[x].sk; }
  }
  if(!best) return null;
  return { sk: best, tg: best.masses ? [i] : [], c: actualCostOf(best, t, cfg.trait), nt: Math.max(0, t + best.tempDelta), overP: 0, ldp: bq };
}

// ---- 戻りの地金: 全マスがゾーンに入った後のやり直し(er、既定 1) ----
// 理想値以上のマスに会心が出ても動かない(miss)ので、ゾーン内のマスにねらい打ちをしても、会心なら
// 「理想値で止まる」か「動かない」かのどちらかで、悪くならない。会心でなければ超過しうるが、戻りで取り戻せる。
// そこで、やめた場合と、マス i に狙い系の1マス技をもう1回打った場合の大成功の確率を比べ、
// 上がる見込みが P.erM を超える時だけ打つ。
//   ・やめた場合: マス i の理想値の見込み(G.posts)と、ほかのマスの誤差の分布(finishedErrDist)から求める。
//   ・打った場合: 会心・ロールごとに結果を求める。ゾーン内に止まれば上と同じ求め方。超過したら、
//     残り1マスの総当たりの表(戻りの地金の版)で、その後の仕上げの見込みを求める(理想値はゾーン内で一様とみなす)。
// 理想値の見込み(実際の局面は G.posts)。先読みの試行の中では、試行の中で分かったことを重ねたものを渡す(postOf)
function redoPost(i, m){
  const n = m.zoneHigh - m.zoneLow + 1;
  return (G.posts && G.posts[i] && G.posts[i].length === n) ? G.posts[i] : null;
}
// 先読みの試行の中の理想値の見込み。試行の中で動いていないマスは G.posts のまま。
// 会心で理想値に止まったマスは確定(ex)、会心で動かなかったマスは「理想値は今の値以下」(le)。
function rolloutPost(i, m){
  const base = redoPost(i, m);
  if(!m.tch) return base;
  const n = m.zoneHigh - m.zoneLow + 1;
  if(m.ex && m.current >= m.zoneLow && m.current <= m.zoneHigh){ const a = new Array(n).fill(0); a[m.current - m.zoneLow] = 1; return a; }
  if(m.le && m.current >= m.zoneLow){
    const a = new Array(n).fill(0); let s = 0;
    for(let k = 0; k < n && m.zoneLow + k <= m.current; k++){ a[k] = base ? base[k] : 1; s += a[k]; }
    if(s > 0) return a.map(x => x / s);
  }
  return base;
}
function endRedo(ms, f, t, P, cfg, postOf){
  const roll = IN_ROLLOUT > 0;
  if(cfg.trait !== 'modori' || !(P.er > 0) || isStartState()) return null;
  if(roll && !(P.erRoll > 0)) return null;
  if(!boardDone(ms, cfg.trait)) return null;
  if(t % 50 !== 0 || t < 50 || t > LDP_TMAX) return null;
  postOf = postOf || redoPost;
  const th = SUCCESS_THRESHOLD, ti = t / 50 - 1, F0 = Math.min(f, roll ? (P.ldpFR || 80) : (P.ldpF || 120));
  const errAt = (v, u) => Math.min(Math.abs(v - u), MAX_ERR);
  // マスごとの誤差の分布(0〜MAX_ERR)
  const ed = ms.map((m, j) => {
    if(m.zoneHigh <= 0) return null;
    const n = m.zoneHigh - m.zoneLow + 1, p = postOf(j, m), e = new Array(MAX_ERR + 1).fill(0);
    for(let k = 0; k < n; k++) e[errAt(m.current, m.zoneLow + k)] += p ? p[k] : 1 / n;
    return e;
  });
  let best = null, bg = P.erM || 0;
  for(let i = 0; i < ms.length; i++){
    const m = ms[i]; if(m.zoneHigh <= 0) continue;
    const L = m.zoneLow, H = m.zoneHigh, n = H - L + 1, cur = m.current;
    const po = postOf(i, m);
    const pu = k => po ? po[k] : 1 / n;
    // ほかのマスの誤差の合計の分布(許容誤差を超える分は捨てる)
    let dist = [1];
    for(let j = 0; j < ms.length; j++){
      if(j === i || !ed[j]) continue;
      const nd = new Array(th + 1).fill(0);
      for(let x = 0; x < dist.length; x++) for(let y = 0; y <= MAX_ERR; y++) if(x + y <= th) nd[x + y] += dist[x] * ed[j][y];
      dist = nd;
    }
    const D = []; let acc = 0; for(let k = 0; k <= th; k++){ acc += dist[k] || 0; D.push(acc); }
    const Dx = x => x < 0 ? 0 : D[Math.min(x, th)];
    let pStop = 0; for(let k = 0; k < n; k++) pStop += pu(k) * Dx(th - errAt(cur, L + k));
    if(pStop > 1 - 1e-9) continue;
    // 超過した後の仕上げの見込みに使う表。先読みの中は一番ありそうな許容誤差の表1枚だけにする
    const mix = [];
    if(roll){
      let kb = -1; for(let k = 0; k <= th; k++) if((dist[k] || 0) > 1e-6 && (kb < 0 || dist[k] > dist[kb])) kb = k;
      if(kb >= 0){ const tb = ldpTable(L, H, Math.min(th - kb, MAX_ERR), cfg); ldpEnsureM(tb, F0); mix.push({ w: D[th], tb }); }
    } else for(let k = 0; k <= th; k++){
      if((dist[k] || 0) <= 1e-6) continue;
      const tb = ldpTable(L, H, Math.min(th - k, MAX_ERR), cfg);
      ldpEnsureM(tb, F0); mix.push({ w: dist[k], tb });
    }
    if(!mix.length) continue;
    ldpTrim(mix.map(e => e.tb));
    for(const act of mix[0].tb.acts){
      if(!act.sk.crit || act.sk.masses !== 1) continue;
      const row = act.rows[ti];
      if(row.skip || row.c > f || !row.r) continue;
      const F2 = Math.min(f - row.c, F0), nti = row.nti, md = nti >= 0 && (nti + 1) % 4 === 0;
      const r = row.r, cr = row.cr;
      let q = 0;
      for(let k = 0; k < n; k++){
        const w = pu(k); if(w <= 0) continue;
        const u = L + k;
        let s = 0;
        for(const x of r){
          // 会心: 理想値が上なら理想値で止まる(届かなければ手前のゾーン内)、理想値以上なら動かない
          const vc = u > cur ? Math.min(cur + 2*x, u) : cur;
          const qc = Dx(th - errAt(vc, u));
          // 会心でない: ゾーン内ならそこで終わり。超過したら表で仕上げの見込みを引く
          const vn = cur + x;
          let qn;
          if(vn <= H) qn = Dx(th - errAt(vn, u));
          else { qn = 0; for(const e of mix) qn += e.w * ldpAfterM(e.tb, e.tb.V[F2], nti, md, vn); }
          s += cr * qc + (1 - cr) * qn;
        }
        q += w * s / r.length;
      }
      const g = q - pStop;
      if(g > bg){ bg = g; best = { sk: act.sk, tg: [i], c: row.c, nt: Math.max(0, t + act.sk.tempDelta), overP: 1, redo: true, er: q, erStop: pStop }; }
    }
  }
  return best;
}

// ---- 2マス残り: ゾーンに近い方を総当たりの最善で仕上げる(ldp2、既定 0。実験) ----
// もう1マスのために集中力を ldp2R × そのマスの残り距離 + ldp2C だけ残し、残りの集中力で計算する。
// このマスに許す誤差は、仕上がったマスの誤差を引いた残りから、もう1マスの分 ldp2B を差し引いたもの。
// もう1マスには当てない(2マスを同時に打つ技は使わない)。戻りの地金でも、戻りは近い方のマスに来る。
function twoMassMove(ms, f, t, P, cfg){
  if(isStartState()) return null;
  const open = [];
  for(let j = 0; j < ms.length; j++){
    if(ms[j].zoneHigh <= 0) continue;
    if(ms[j].current > ms[j].zoneHigh) return null;
    if(ms[j].current < ms[j].zoneLow) open.push(j);
  }
  if(open.length !== 2) return null;
  const gap = j => ms[j].zoneLow - ms[j].current;
  const [i, j] = gap(open[0]) <= gap(open[1]) ? open : [open[1], open[0]];
  const p = gap(i);
  if(p < 1 || p > LDP_GMAX || t % 50 !== 0 || t < 50 || t > LDP_TMAX) return null;
  const F = Math.min(f - Math.round((P.ldp2R || 0) * gap(j) + (P.ldp2C || 0)), P.ldpF || 120);
  if(F < 5) return null;
  const th = SUCCESS_THRESHOLD, dist = finishedErrDist(ms, i, th, j);
  if(!dist) return null;
  const mod = cfg.trait === 'modori', ti = t / 50 - 1, mix = [];
  for(let k = 0; k <= th; k++){
    const a = th - k - (P.ldp2B || 0);
    if(dist[k] <= 1e-6 || a < 0) continue;
    const tb = ldpTable(ms[i].zoneLow, ms[i].zoneHigh, Math.min(a, MAX_ERR), cfg);
    if(mod) ldpEnsureM(tb, F); else ldpEnsure(tb, F);
    mix.push({ w: dist[k], tb });
  }
  if(!mix.length) return null;
  ldpTrim(mix.map(e => e.tb));
  let best = null, bq = 0;
  for(let x = 0; x < mix[0].tb.acts.length; x++){
    if(undoesPrev(mix[0].tb.acts[x].sk, cfg)) continue;
    let q = 0, ok = true;
    if(!mod) q = ldpQNoUndo(mix, x, ti, p, F, cfg);
    if(q < 0) ok = false;
    else if(mod) for(const e of mix){ const v = ldpQM(e.tb, e.tb.acts[x], ti, p, F); if(v < 0){ ok = false; break; } q += e.w * v; }
    if(ok && q > bq){ bq = q; best = mix[0].tb.acts[x].sk; }
  }
  if(!best) return null;
  return { sk: best, tg: best.masses ? [i] : [], c: actualCostOf(best, t, cfg.trait), nt: Math.max(0, t + best.tempDelta), overP: 0 };
}

function traitTempState(temp){
  const mod400 = temp % 400 === 0;
  const mod200 = temp % 200 === 0 && !mod400;
  return { mod400, mod200 };
}

function getPowerMultiplier(trait, temp, isLitMass){
  if(!traitActive(temp)) return 1;      // 1手目は地金特性が乗らない
  const st = traitTempState(temp);
  if(trait === 'tataki'){
    if(st.mod400) return 2;
    if(st.mod200) return 0.5;
    return 1;
  }
  if(trait === 'kaishin' && isLitMass && (st.mod400 || st.mod200)){
    return 2;
  }
  return 1;
}

// 点灯しているマスの番号。kaishin 以外では常に null なので、
// 下の2つの入口は既存2商材では getRollCandidates(...,false) と完全に同じ値を返す。
let litMassIndex = null;
// ロールアウトの中で、200℃の倍数に来るたびに点灯マスを引き直す。
// 実機は未到達マスからランダムに1つ選ぶ(再抽選)。
// 現在の手番だけは実際に光っているマスが分かっているので触らない。
function rollLit(ms, temp, trait, rnd){
  if(trait !== 'kaishin'){ litMassIndex = null; return; }
  if(temp % 200 !== 0 || temp <= 0){ litMassIndex = null; return; }
  const cand = [];
  for(let i = 0; i < ms.length; i++) if(ms[i].current < ms[i].zoneLow) cand.push(i);
  litMassIndex = cand.length ? cand[(rnd()*cand.length)|0] : null;
}
function clearLit(){ litMassIndex = null; }
function isLitAt(trait, i){
  return trait === 'kaishin' && litMassIndex !== null && litMassIndex === i;
}
function rollsForMass(skill, temp, trait, i){
  return getRollCandidates(skill, temp, trait, isLitAt(trait, i));
}
function critForMass(skill, cfg, temp, i){
  if(HS === 2 && skill && skill.key) return 1;       // 必殺(ヘパイトスの炎)の後は、次に叩く技が必ず会心
  return computeCritRate(skill, cfg.level, cfg.hammerId, cfg.star, cfg.trait, temp, isLitAt(cfg.trait, i));
}

/* 威力の計算式(検証済み)
   1000℃時の基準値 n に対して   値 = ceil( n × (0.0005 × min(温度,2000) + 0.5) )
   係数は 350℃で0.675、1000℃で1.0、2000℃で1.5。2000℃を超えても頭打ち。
   候補は「最小と最大を等分」ではなく、基準 n の整数を1つずつ当てはめた結果になる。
   実測テーブル(tests/power-table.js)の最大・最小248点はすべてこの式で再現できる。
   照合は tests/sim.js が毎回行う。 */
/* ロールは常に7通り。計算式は
     会心 × ceil( 特性 × ceil( (0.5 + 0.0005×温度) × ceil(n × 技倍率) ) )
   n は「たたく」の 12〜18。温度は2000℃で頭打ち。
   技倍率 y は てかげん0.5 / みだれ0.8 / 通常1 / 上下・4連・ななめ1.2 /
   2倍・超4連2 / 熱風2.5 / 3倍3。端数はいずれも切り上げ。
   特性(たたき変化)は 1・2・0.5、会心は最後に2倍する。
   6系列すべての最小値と最大値が実測テーブルと一致することを確認済み。 */
const SKILL_MULT = { tataku:1, tekagen:0.5, joge:1.2, nibai:2, sanbai:3, reppu:2.5, midare:0.8 };
const BASE_N = {};   // 1000℃時の7通り
(function(){
  for(const key of Object.keys(SKILL_MULT)){
    const m = SKILL_MULT[key], v = [];
    for(let n = 12; n <= 18; n++) v.push(Math.ceil(n * m));
    BASE_N[key] = v;
  }
  // 上下系(上下打ち・4連打ち・ななめ打ち・左右打ち・上下ねらい打ち)の4番目を実測で補正。
  // 式では 15×1.2 = 18.0 ちょうどとなり切り上げても18だが、実機は19。
  // 根拠となった観測(いずれも1000℃時の基準19が必要):
  //   2050℃ 4連打ち → 29 / 1800℃ 上下ねらい打ち → 27
  // 最小15・最大22は変わらないため、実測テーブルとの照合には影響しない。
  BASE_N.joge = [15, 16, 17, 19, 20, 21, 22];
})();
// 係数 (0.5 + 0.0005x) は (1000 + x) / 2000 と同じ。
// 小数で計算すると 0.0005*1400 が 0.7000000000000001 になり、
// 切り上げの結果が1ずれるため、整数の分子分母で扱う。
function tempNum(temp){ return 1000 + Math.max(50, Math.min(2000, temp)); }
function scaleUp(base, temp){ return Math.ceil(base * tempNum(temp) / 2000); }
function baseValues(key){ return BASE_N[key] || null; }

// 盤面は横2列。縦は3行(6マス)が基本で、7〜8マスの商材(両手剣・ムチ・からだ下など)は4行。setActiveMask で商材ごとに決まる
let GRID_ROWS = 3;
const GRID_COLS = 2;
// 大成功の許容誤差(誤差合計)。商材の盤面の形で決まるため、素材を切り替えるたびに設定し直す。
// 出典: 公式ガイドブックを元にした種別ごとの表(6マスの練金ツボ・家具=7、盾・アタマ=3 など)。
// 手動設定では、使うマスの数で決める(利用者の指示。2マス=0・3マス=2・4マス=3・5マス=5・6マス=7。
// 幽紋刀・ブルームシールド・光の鍛冶ハンマー・6マスの素材と同じ値)。7・8マス(8マスの盤)は 9・10
// (追加した商材で、種類の表に無いものに使う値と同じ。CRAFT_ITEMS の読み込みの TH)。
let SUCCESS_THRESHOLD = 7;
const DEFAULT_THRESHOLD = 7;
const THRESHOLD_BY_MASSES = [0, 0, 0, 2, 3, 5, 7, 9, 10];     // 添字 = 使うマスの数
function thresholdForMasses(n){ return THRESHOLD_BY_MASSES[Math.max(0, Math.min(THRESHOLD_BY_MASSES.length - 1, n))]; }
// 素材ごとの設定(許容誤差と、評価の重みの上書き)を反映する。素材を切り替えた時に呼ぶ。
function applyThreshold(){
  // 評価の重みは既定値に戻してから、素材に上書きがあれば重ねる
  if(typeof BASE_PARAMS !== 'undefined'){
    for(const k of Object.keys(PARAMS)) delete PARAMS[k];
    Object.assign(PARAMS, BASE_PARAMS);
    const pp = PRESETS[G.preset];
    if(pp && pp.params) Object.assign(PARAMS, pp.params);
  }
  if(G.preset === 'custom'){
    SUCCESS_THRESHOLD = Array.isArray(G.masses) ? thresholdForMasses(G.masses.filter(m => !m.off).length) : DEFAULT_THRESHOLD;
    return;
  }
  const p = PRESETS[G.preset];
  SUCCESS_THRESHOLD = (p && typeof p.threshold === 'number') ? p.threshold : DEFAULT_THRESHOLD;
}
const MAX_ERR = 4;                  // ゾーン内の誤差キャップ
// ゾーンを超えたマスの誤差の下限。公開情報「成功ゾーン内は差が5以上でも4扱い、
// 逆に成功ゾーン外は必ず誤差9以上扱い」に基づく。許容7の6マス商材では、
// 1マスでも超過すれば大成功にならない。
const OVER_ERR_MIN = 9;
// 1マスの誤差。成功判定・期待誤差の計算はすべてこの関数を通す。
// (以前は箇所ごとに書き方が違い、超過マスを実差のまま数える箇所が残っていた)
function massError(current, ideal, zoneLow, zoneHigh){
  const raw = Math.abs(current - ideal);
  if(current >= zoneLow && current <= zoneHigh) return Math.min(raw, MAX_ERR);
  if(current > zoneHigh) return Math.max(raw, OVER_ERR_MIN);
  return raw;                        // 未到達。成功判定では別途「失敗」として扱う
}

// 推奨手の重み。すべて実測(各数千〜1.5万回のシミュレーション)で決めた値。
//   cap  : 会心が理想値を捉える見込み
//   adv  : 前進量あたりの効率
//   land : 特殊温度に着地することの価値
//   heat : 温度不足で火力上げに切り替える閾値
//   ov   : ゾーン超過のリスク(超過は回復不能)
//   pr   : 遅れているマスを優先する度合い
//   te   : 本会心ゾーンにいるマスを狙い打つ価値
//   rush : 会心の見込みが無いマスをゾーンへ押し込む手の抑制
//   save : 消費半減ターンで、節約額の大きい技を選ぶ度合い
//   turn : 特殊温度(会心+400% / 消費半減)に乗る手を優先する度合い
//   litReady : 点灯の抽選(200の倍数)に、点灯したら仕上げられる位置で臨む度合い(威力会心率上昇のみ)
//   lastDP / lastDProll : 残り1マスを総当たりの最善で仕上げる / 先読みの中の打ち手でも使う(1で使う。全商材・手動設定の既定)
//   ldpF / ldpFR : その計算で見る集中力の上限(既定 120 / 先読みの中 80)
//   er   : 戻りの地金で、全マスがゾーンに入った後もやり直しの見込みを計算する(endRedo。1で使う。全商材・手動設定の既定。
//          戻り以外の地金では何もしない)
//   hsSetup : 必殺がチャージ済みの間、超4連打ちの形の4マスを詰めてから使う(hsDecide。1で使う。全商材・手動設定の既定)
//   boostEff : 会心ターンの狙い打ち(boostAim)の前に、残るマスの残り距離の合計 ÷ boostEff の集中力を残す(既定 0 = 見ない)
//   psEff : 2マス同時の本会心(pairSnipe)の前に、残るマスの残り距離の合計 ÷ psEff の集中力を残す(既定 0 = 見ない)
/* 評価パラメータ。素材ごとの効き方は検証済み(0にした時に結果が変わる対局の割合)。
   両方       cap adv land heat ov pr tmax te center far mpm slack effK slackMax
              rush wideAim pairSnipe
   樹液のみ    save(39.7%) turn(8.4%) boostPlan(3.6%) saveCap boostAim boostRes
   いとのみ    opening(51.0%) center(16.4%) tatakiFit(5.1%) x2turn aimNow aimRes
   ※ 樹液=超かがやきの樹液(集中力変化) / いと=超あまつゆのいと(たたき変化) */
const PARAMS = { cap:12, adv:0.75, land:3, heat:4, ov:4, pr:0.8, tmax:2200,
                 te:5, rush:0.6, save:25, turn:5, tatakiFit:1.5, boostPlan:1, center:3, opening:1, wideAim:2, pairSnipe:1, far:5, mpm:16, slack:1, effK:4, slackMax:2, saveCap:0.7, boostAim:0.7, boostRes:24, x2turn:10, aimNow:1, aimRes:2.2,
                 lastDP:1, lastDProll:1, er:1, hsSetup:1 };
// 既定の重み。素材ごとの上書き(PRESETS の params)は applyThreshold が重ねる。
const BASE_PARAMS = Object.freeze(Object.assign({}, PARAMS));

function rcToIdx(r,c){
  if(r<0||r>=GRID_ROWS||c<0||c>=GRID_COLS) return null;
  return r*GRID_COLS+c;
}

// 技ごとの対象マスの組み合わせを、盤面の隣接関係に沿って列挙する
// 盤面に存在しないマス(使わないマス)にはみ出す形は打てない(実ゲームの挙動)。
// 例: 2×2の盾で、超4連打ちを下段2マスだけに当てることはできない。
// ただし4連打ち・超4連打ちは、使うマスを囲む枠の中の空きマスや、1列だけの盤の隣の列は含めて打てる(利用者の情報)。
// ※以前は「残ったマスだけを対象に打てる」としていたが、実際には打てないとの指摘を受けて戻した
//   (引き継ぎ資料 v116)。ゾーンに到達済みのマスを含む形は、盤面上に存在するので打てる。
let ACTIVE = null;                       // null = 全マス有効
function setActiveMask(list){
  if(Array.isArray(list)) GRID_ROWS = Math.max(3, Math.ceil(list.length / GRID_COLS));
  ACTIVE = (Array.isArray(list) && list.some(v => !v)) ? list.slice() : null;
}
function isActive(i){ return !ACTIVE || ACTIVE[i]; }
function enumerateTargetSets(skill){
  const sets = [];
  if(skill.masses===0) return [[]];
  if(skill.masses===1){
    for(let i=0;i<GRID_ROWS*GRID_COLS;i++) if(isActive(i)) sets.push([i]);
    return sets;
  }
  for(let r=0;r<GRID_ROWS;r++){
    for(let c=0;c<GRID_COLS;c++){
      const base = rcToIdx(r,c);
      if(base===null) continue;
      if(skill.shape==='vertical'){
        const b = rcToIdx(r+1,c);
        if(b!==null) sets.push([base,b]);
      } else if(skill.shape==='horizontal'){
        const b = rcToIdx(r,c+1);
        if(b!==null) sets.push([base,b]);
      } else if(skill.shape==='diagonal'){
        const b = rcToIdx(r+1,c-1);
        if(b!==null) sets.push([base,b]);
      } else if(skill.shape==='square'){
        const a=rcToIdx(r,c), b=rcToIdx(r,c+1), d=rcToIdx(r+1,c), e=rcToIdx(r+1,c+1);
        if(a!==null&&b!==null&&d!==null&&e!==null) sets.push([a,b,d,e]);
      }
    }
  }
  if(!ACTIVE) return sets;
  if(skill.shape !== 'square'){
    // 存在しないマスを1つでも含む形は、盤面からはみ出すので打てない
    return sets.filter(g => g.every(i => ACTIVE[i]));
  }
  // 4連打ち・超4連打ちは、使うマスを囲む枠の中なら、空いたマスを含んでも打てる
  // (空いたマスには効果が無いので、対象から落とす)。例: マス1〜3だけで4が空いた盤。
  // 使うマスが1列だけの盤(片手剣など)は、その列の縦に並んだ2マスだけに当てられる。
  // 枠の外にはみ出す形は、これまでどおり打てない(例: 2×2の盾の下段2マスだけ)。
  let r0 = GRID_ROWS, r1 = -1, c0 = GRID_COLS, c1 = -1;
  for(let i = 0; i < GRID_ROWS*GRID_COLS; i++){
    if(!ACTIVE[i]) continue;
    const r = Math.floor(i / GRID_COLS), c = i % GRID_COLS;
    r0 = Math.min(r0, r); r1 = Math.max(r1, r); c0 = Math.min(c0, c); c1 = Math.max(c1, c);
  }
  const oneCol = c0 === c1;
  const seen = new Set(), out = [];
  for(const g of sets){
    const inFrame = g.every(i => {
      const r = Math.floor(i / GRID_COLS), c = i % GRID_COLS;
      return r >= r0 && r <= r1 && (oneCol || (c >= c0 && c <= c1));
    });
    if(!inFrame) continue;
    const t = g.filter(i => ACTIVE[i]);
    if(!t.length) continue;
    const key = t.join(',');
    if(seen.has(key)) continue;
    seen.add(key); out.push(t);
  }
  return out;
}

// 地金特性「集中力変化」による消費の増減
//  400の倍数 → 消費半減 / 200の倍数(400除く) → 消費1.5倍だが会心率+400%
function traitActive(temp){
  return !isStartState();
}
function actualCostOf(sk, temp, trait){
  if(!sk.cost) return 0;                     // 必殺は集中力を使わない
  if(trait!=='shuchu') return sk.cost;
  if(!traitActive(temp)) return sk.cost;     // 開始直後は特性が乗らない
  if(temp%400===0) return Math.max(1, Math.round(sk.cost*0.5));
  if(temp%200===0) return Math.round(sk.cost*1.5);
  return sk.cost;
}
// 消費半減 / 会心率+400% は地金特性「集中力変化」でのみ発生する。
// 他の特性(たたき変化など)では、同じ温度でも別の効果になるため false を返す。
const isHalfTurn  = t => traitActive(t) && G.trait==='shuchu' && t%400===0;
const isBoostTurn = t => traitActive(t) && G.trait==='shuchu' && t%200===0 && t%400!==0;

// たたき変化:400の倍数で威力2倍、200の倍数(400除く)で威力半減
const isPowerUpTurn   = t => traitActive(t) && G.trait==='tataki' && t%400===0;
const isPowerDownTurn = t => traitActive(t) && G.trait==='tataki' && t%200===0 && t%400!==0;

// その温度・技での7候補のロール値(整数、四捨五入)
function getRollCandidates(skill, temp, trait, isLit){
  if(!skill.key) return null;
  const ns = baseValues(skill.key);
  if(!ns) return null;
  const mult = getPowerMultiplier(trait, temp, isLit);
  const out = [];
  for(let k=0;k<7;k++){                        // 候補は常に7通り
    const v = scaleUp(ns[k], temp);
    out.push((mult === 1) ? v : Math.ceil(v * mult));
  }
  return out;
}

// ---- みだれ打ち ----
// 使うマス全部から1回ずつ等確率で選んで4回叩く。k回当たった時の伸びの合計の分布(会心は1回ごとに判定、
// 会心で理想値に止まる効果は見ない=超過の見積もりは保守的)を、温度・ロール・会心率ごとに覚えておく。
const MIDARE_HITS = 4;
const MIDARE_SAFE = 0.01;
const MIDARE_DIST = new Map();
function midareSumDist(r, cr, k){
  const key = r.join(',') + '|' + cr + '|' + k;
  let d = MIDARE_DIST.get(key);
  if(d) return d;
  d = new Map([[0, 1]]);
  for(let h = 0; h < k; h++){
    const nd = new Map();
    for(const [v, p] of d) for(const x of r){
      const q = p / r.length;
      nd.set(v + x, (nd.get(v + x) || 0) + q * (1 - cr));
      nd.set(v + 2*x, (nd.get(v + 2*x) || 0) + q * cr);
    }
    d = nd;
  }
  if(MIDARE_DIST.size > 4000) MIDARE_DIST.clear();
  MIDARE_DIST.set(key, d);
  return d;
}
function binomP(n, k, p){
  let c = 1; for(let i = 0; i < k; i++) c = c * (n - i) / (i + 1);
  return c * Math.pow(p, k) * Math.pow(1 - p, n - k);
}
// みだれ打ちの手。tg は使うマス全部(どこに当たるかは打つまで分からない)。
// advE: 未到達のマスが進む量の期待値(ゾーン下限で頭打ち) / overP: どれかのマスが超過する、
// またはゾーンに入っているマスに当たって値が動く確率の最大 / prioE: 残り距離の割合の期待値。
function midareMove(ms, f, t, cfg, sk){
  const c = actualCostOf(sk, t, cfg.trait);
  if(c > f) return null;
  const nt = Math.max(0, t + sk.tempDelta);
  if(nt <= 0) return null;
  const act = [];
  for(let i = 0; i < ms.length; i++) if(ms[i].zoneHigh > 0 && isActive(i)) act.push(i);
  if(!act.length) return null;
  const p = 1 / act.length;
  let advE = 0, overP = 0, prioE = 0;
  for(const i of act){
    const m = ms[i];
    const r = rollsForMass(sk, t, cfg.trait, i);
    if(!r) return null;
    const cr = critForMass(sk, cfg, t, i);
    const gap = m.zoneLow - m.current, room = m.zoneHigh - m.current;
    let pOver = 0, eAdv = 0;
    for(let k = 1; k <= MIDARE_HITS; k++){
      const pk = binomP(MIDARE_HITS, k, p);
      if(gap <= 0){ pOver += pk; continue; }        // ゾーンに入っているマスは、当たれば値が動く
      for(const [v, q] of midareSumDist(r, cr, k)){
        if(v > room) pOver += pk * q;
        eAdv += pk * q * Math.min(v, gap);
      }
    }
    if(gap > 0){ advE += eAdv; prioE += (MIDARE_HITS * p) * gap / Math.max(1, m.zoneLow); }
    overP = Math.max(overP, pOver);
  }
  return { sk, tg: act, c, nt, overP, advE, prioE };
}
// 手を打った時に叩かれるマスの並び。みだれ打ちは使うマスからランダムに4回、それ以外は対象のマスそのもの。
function hitSeq(mv, rnd){
  if(!mv.sk.random) return mv.tg;
  const out = [];
  for(let h = 0; h < MIDARE_HITS; h++) out.push(mv.tg[Math.floor(rnd() * mv.tg.length)]);
  return out;
}

// 超過リスクのあるマスは「今は触らない」のが正解。
// 全体の温度を下げると他マスの効率まで落ちるが、そのマスを後回しにして
// 他を進めれば、打撃のたびに温度は自然に下がり、やがて安全圏に入る。
// 冷やし込みが要るとしても、他が片付いた最後の場面に限られる。
function moves(ms,f,t,cfg){
  const strict=[], loose=[];
  for(const sk of SKILLS){
    if(sk.lv>cfg.level)continue;
    if(sk.random){
      if(!PARAMS.midare) continue;      // 運の要素が大きいので、素材の params で midare:1 を入れた時だけ使う(幽紋刀のみ)
      const mv = midareMove(ms, f, t, cfg, sk);
      // 4回とも会心で大きく伸びた時だけ超える、のような僅かな確率は安全とみなす(MIDARE_SAFE 以下)
      if(mv) (mv.overP <= MIDARE_SAFE ? strict : loose).push(mv);
      continue;
    }
    const c=actualCostOf(sk,t,cfg.trait);
    if(c>f)continue;
    const nt=Math.max(0,t+sk.tempDelta);
    if(nt<=0)continue;
    if(sk.masses===0){ strict.push({sk,tg:[],c,nt,overP:0}); continue; }
    if(!getRollCandidates(sk,t,cfg.trait,false))continue;
    for(const tg of enumerateTargetSets(sk)){
      if(tg.some(i=>ms[i].current>=ms[i].zoneLow))continue;
      let maxOver=0;
      for(const i of tg){
        // 点灯マスはロールが2倍。共通のロールで判定すると超過を見逃す
        const r=rollsForMass(sk,t,cfg.trait,i);
        if(!r) continue;
        let cnt=0;
        for(const x of r) if(ms[i].current+x>ms[i].zoneHigh) cnt++;
        maxOver=Math.max(maxOver,cnt/r.length);
      }
      const mv={sk,tg,c,nt,overP:maxOver};
      if(maxOver===0) strict.push(mv);
      else loose.push(mv);
    }
  }
  if(strict.some(m=>m.sk.masses>0)) return strict;
  // 安全に打てる打撃手が無い = 未到達マスがすべて超過圏にある状態。
  // ここまで来て初めて冷やし込みに価値が出る(他マスへの巻き添えがないため)。
  // たたき変化では火力上げも同じ役に立つ。半減ターン(200の倍数)に上げればロールが縮む
  // (例: 700℃で残り1のマスは、火力上げで1000℃にすればてかげん打ち3〜5で収まる)。
  const cool=[];
  for(const sk of SKILLS){
    if(sk.lv>cfg.level||sk.masses!==0||sk.tempDelta===0)continue;
    const c=actualCostOf(sk,t,cfg.trait);
    if(c>f)continue;
    const nt=Math.max(0,t+sk.tempDelta);
    if(nt<=0)continue;
    // 下げた先で安全に打てるようになるか
    let ok=false;
    for(const s2 of SKILLS){
      if(s2.lv>cfg.level||s2.masses===0||s2.id==='midare')continue;
      const r2=getRollCandidates(s2,nt,cfg.trait,false);
      if(!r2||actualCostOf(s2,nt,cfg.trait)>f-c)continue;
      for(const tg2 of enumerateTargetSets(s2)){
        if(tg2.some(i=>ms[i].current>=ms[i].zoneLow))continue;
        let safe=true;
        for(const i of tg2) if(ms[i].current+r2[r2.length-1]>ms[i].zoneHigh){safe=false;break;}
        if(safe){ok=true;break;}
      }
      if(ok)break;
    }
    if(ok) cool.push({sk,tg:[],c,nt,overP:0,cooling:true});
  }
  if(cool.length>0) return strict.concat(cool);
  // ここに来た = 安全に打てる手も冷却で解決する手も無く、
  // 超過覚悟で撃つしかない状態。だがその前に、温度を下げれば
  // ロール値そのものが縮んで収まる可能性がある。
  // 残り1のマスは500℃以下、残り2は700℃以下でないと収まらないため、
  // 冷却が複数回必要なこともある。集中力が許すなら冷却を優先する。
  const rescue=[];
  for(const sk of SKILLS){
    if(sk.lv>cfg.level||sk.id==='midare')continue;
    if(sk.tempDelta>=0)continue;
    const c=actualCostOf(sk,t,cfg.trait);
    if(c>f)continue;
    const nt=Math.max(0,t+sk.tempDelta);
    if(nt<=0)continue;
    // 下げ続ければ最終的に収まるか(集中力が尽きるまで試算)
    let tt=nt, ff=f-c, reachable=false;
    for(let k=0;k<8;k++){
      let ok=false;
      for(const m of ms){
        if(m.current>=m.zoneLow)continue;
        for(const s2 of SKILLS){
          if(s2.lv>cfg.level||s2.masses===0||s2.id==='midare')continue;
          const r2=getRollCandidates(s2,tt,cfg.trait,false);
          if(!r2)continue;
          if(actualCostOf(s2,tt,cfg.trait)>ff)continue;
          if(m.current+r2[r2.length-1]<=m.zoneHigh){ok=true;break;}
        }
        if(ok)break;
      }
      if(ok){reachable=true;break;}
      const c2=actualCostOf(sk,tt,cfg.trait);
      if(c2>ff||tt+sk.tempDelta<=0)break;
      ff-=c2; tt=Math.max(0,tt+sk.tempDelta);
    }
    if(!reachable)continue;
    if(sk.masses===0){ rescue.push({sk,tg:[],c,nt,overP:0,cooling:true}); }
    else{
      if(!getRollCandidates(sk,t,cfg.trait,false))continue;
      let added=false;
      for(const tg of enumerateTargetSets(sk)){
        if(tg.some(i=>ms[i].current>=ms[i].zoneLow))continue;
        let safe=true;
        for(const i of tg){
          const r=rollsForMass(sk,t,cfg.trait,i);
          if(r&&ms[i].current+r[r.length-1]>ms[i].zoneHigh){safe=false;break;}
        }
        if(safe){ rescue.push({sk,tg,c,nt,overP:0,cooling:true}); added=true; }
      }
      // 対象マスを持つ技を「対象なし」で出してはいけない。
      // 熱風おろしはロールがたたくの約2.5倍あり、実際に撃てば必ずどこかのマスが伸びる。
      // 対象なしで出すと、その前進量が計算から消えたまま推奨されることになり、
      // プレイヤーが実行した瞬間に盤面と予測がずれる。
      // 安全な対象が無い場合は、超過が最も小さい対象を選び、その超過リスクを明示する。
      // ただし必ず超過する手は救いにならない(超過は大成功を失う)ので出さない。
      // 出すと、超過の確率がもっと低い手(下の loose)が候補から消えてしまう。
      if(!added){
        let bestTg = null, bestOv = Infinity;
        for(const tg of enumerateTargetSets(sk)){
          if(tg.some(i=>ms[i].current>=ms[i].zoneLow))continue;
          let ov = 0;
          for(const i of tg){
            const r = rollsForMass(sk, t, cfg.trait, i);
            if(!r) continue;
            let cnt = 0;
            for(const x of r) if(ms[i].current+x>ms[i].zoneHigh) cnt++;
            ov = Math.max(ov, cnt/r.length);
          }
          if(ov < bestOv){ bestOv = ov; bestTg = tg; }
        }
        if(bestTg && bestOv < 1) rescue.push({sk,tg:bestTg,c,nt,overP:bestOv,cooling:true});
      }
    }
  }
  if(rescue.length>0) return strict.concat(rescue);
  loose.sort((a,b)=>a.overP-b.overP);
  return strict.concat(loose.slice(0,12));
}
